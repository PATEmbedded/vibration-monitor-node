"""Write model/model_data.h from model/model.json.

    python tools/export_header.py           # write the header
    python tools/export_header.py --check   # fail if the committed header is out of date
"""
from __future__ import annotations

import argparse
import json
import sys

from vmnlib import MODEL_JSON

HEADER = MODEL_JSON.parent / "model_data.h"


def c_float(value: float) -> str:
    text = f"{value:.9g}"
    if not any(ch in text for ch in ".en"):
        text += ".0"
    return text + "f"


def c_array(ctype: str, name: str, values, fmt, per_line: int) -> list[str]:
    items = [fmt(v) for v in values]
    lines = [f"static const {ctype} {name}[{len(items)}] = {{"]
    for i in range(0, len(items), per_line):
        lines.append("    " + ", ".join(items[i : i + per_line]) + ",")
    lines.append("};")
    return lines


def render(d: dict) -> str:
    out = [
        "/* Generated by tools/export_header.py from model/model.json. Do not edit by hand. */",
        "#ifndef VMN_MODEL_DATA_H",
        "#define VMN_MODEL_DATA_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define VMN_MODEL_INPUTS {d['inputs']}",
        f"#define VMN_MODEL_HIDDEN {d['hidden']}",
        f"#define VMN_MODEL_CLASSES {len(d['classes'])}",
        f"#define VMN_MODEL_INPUT_SCALE {c_float(d['input_scale'])}",
        f"#define VMN_MODEL_OUTPUT_SCALE {c_float(d['output_scale'])}",
        f"#define VMN_MODEL_M1 INT32_C({d['m1']})",
        f"#define VMN_MODEL_SHIFT1 {d['shift1']}",
        "",
        "/* Standardisation of the features: z = (x - mean) / std. */",
        *c_array("float", "vmn_model_mean", d["feature_mean"], c_float, 5),
        *c_array("float", "vmn_model_std", d["feature_std"], c_float, 5),
        "",
        "/* Hidden layer: weights [hidden][inputs] and int32 biases. */",
        *c_array("int8_t", "vmn_model_w1", d["w1"], str, d["inputs"]),
        *c_array("int32_t", "vmn_model_b1", d["b1"], str, 8),
        "",
        "/* Output layer: weights [classes][hidden] and int32 biases. */",
        *c_array("int8_t", "vmn_model_w2", d["w2"], str, d["hidden"]),
        *c_array("int32_t", "vmn_model_b2", d["b2"], str, 8),
        "",
        "#endif",
        "",
    ]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="compare instead of writing")
    args = ap.parse_args()
    text = render(json.loads(MODEL_JSON.read_text(encoding="utf-8")))
    if args.check:
        current = HEADER.read_text(encoding="utf-8") if HEADER.exists() else ""
        if current != text:
            sys.exit(f"{HEADER} is out of date; run python tools/export_header.py")
        print(f"{HEADER.name} matches {MODEL_JSON.name}")
        return
    HEADER.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {HEADER}")


if __name__ == "__main__":
    main()
